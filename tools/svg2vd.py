#!/usr/bin/env python3
"""Convert the hand-built FAFO wordmark SVGs (flat-fill <path> elements only) to Android VectorDrawables.

Usage: python3 tools/svg2vd.py <in.svg> <out.xml> [width_dp]
Stdlib only. The SVG viewBox becomes the viewport; a negative origin becomes a translated group.
Supports fill, fill-rule and path data (VectorDrawable pathData accepts the same commands, arcs included).
"""
import re
import sys
import xml.etree.ElementTree as ET

NS = "{http://www.w3.org/2000/svg}"


def convert(src: str, dst: str, width_dp: float = 240.0) -> None:
    root = ET.parse(src).getroot()
    minx, miny, w, h = (float(v) for v in root.get("viewBox").split())
    height_dp = round(width_dp * h / w, 1)
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Generated by tools/svg2vd.py from {src.split('/')[-1]}. Do not edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{width_dp}dp"',
        f'    android:height="{height_dp}dp"',
        f'    android:viewportWidth="{w}"',
        f'    android:viewportHeight="{h}">',
        f'    <group android:translateX="{-minx}" android:translateY="{-miny}">',
    ]
    for p in root.iter(NS + "path"):
        d = re.sub(r"\s+", " ", p.get("d")).strip()
        fill = p.get("fill", "#000000").upper()
        rule = "evenOdd" if p.get("fill-rule") == "evenodd" else "nonZero"
        out.append("        <path")
        out.append(f'            android:fillColor="{fill}"')
        out.append(f'            android:fillType="{rule}"')
        out.append(f'            android:pathData="{d}" />')
    out += ["    </group>", "</vector>", ""]
    with open(dst, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    convert(sys.argv[1], sys.argv[2], float(sys.argv[3]) if len(sys.argv) > 3 else 240.0)
