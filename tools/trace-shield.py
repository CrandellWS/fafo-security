#!/usr/bin/env python3
"""Trace the approved FAFO shield PNG into recolorable vector layers for ShieldMark (round 3).

Usage (needs numpy, pillow, scipy and potracer in a throwaway venv; the output is committed, so the
build never depends on this):
    python3 tools/trace-shield.py ~/Pictures/fafo-logo/fafo-shield2-FINAL-1024.png \
        app/src/main/java/ws/crandell/fafo/ui/components/ShieldPaths.kt

The source uses exactly three colors (navy #0B1F35, red #D61018, white) on transparency. Each pixel is
snapped to the nearest one, then the red is split into connected parts by position: the two chevron
stripes (largest parts), the beak (right of center) and the eye (the small part left of the beak).
Layers, bottom to top: silhouette (white sticker edge, field and highlights), navy, stripes, beak, eye.
Each layer is one even-odd SVG path on a 1024 x 1024 viewport.
"""
import sys

import numpy as np
import potrace
from PIL import Image
from scipy import ndimage

PALETTE = {"navy": (11, 31, 53), "red": (214, 16, 24), "white": (255, 255, 255)}


def fmt(v: float) -> str:
    s = f"{v:.1f}"
    return s[:-2] if s.endswith(".0") else s


def trace(mask: np.ndarray) -> str:
    # potracer traces the zero pixels as ink, so hand it the inverted mask.
    bm = potrace.Bitmap(~mask)
    plist = bm.trace(turdsize=8, turnpolicy=potrace.POTRACE_TURNPOLICY_MINORITY, alphamax=1.0, opticurve=True, opttolerance=0.3)
    out = []
    for curve in plist:
        sp = curve.start_point
        out.append(f"M{fmt(sp.x)} {fmt(sp.y)}")
        for seg in curve.segments:
            if seg.is_corner:
                out.append(f"L{fmt(seg.c.x)} {fmt(seg.c.y)}L{fmt(seg.end_point.x)} {fmt(seg.end_point.y)}")
            else:
                out.append(
                    f"C{fmt(seg.c1.x)} {fmt(seg.c1.y)} {fmt(seg.c2.x)} {fmt(seg.c2.y)} {fmt(seg.end_point.x)} {fmt(seg.end_point.y)}"
                )
        out.append("Z")
    return "".join(out)


def main(src: str, dst: str) -> None:
    im = np.array(Image.open(src).convert("RGBA")).astype(int)
    assert im.shape[0] == im.shape[1] == 1024, "expects the 1024 px master"
    alpha, rgb = im[..., 3], im[..., :3]
    dist = np.stack([((rgb - np.array(c)) ** 2).sum(-1) for c in PALETTE.values()], -1)
    cls = dist.argmin(-1)
    solid = alpha >= 128
    navy = solid & (cls == 0)
    red = solid & (cls == 1)

    lab, n = ndimage.label(red)
    parts = sorted(((int((lab == i).sum()), i) for i in range(1, n + 1)), reverse=True)
    stripes = np.isin(lab, [parts[0][1], parts[1][1]])
    rest = [i for _, i in parts[2:] if (lab == i).sum() > 200]
    centers = {i: ndimage.center_of_mass(lab == i) for i in rest}
    beak_id = max(rest, key=lambda i: (lab == i).sum())  # the beak is the larger of the remaining parts
    eye_ids = [i for i in rest if i != beak_id and centers[i][1] < centers[beak_id][1]]
    beak = lab == beak_id
    eye = np.isin(lab, eye_ids)
    # Specks too small to matter (anti-aliasing) stay in the navy layer.
    navy |= red & ~(stripes | beak | eye)

    layers = {
        "SILHOUETTE": solid,
        "NAVY": navy,
        "STRIPES": stripes,
        "BEAK": beak,
        "EYE": eye,
    }
    lines = [
        "package ws.crandell.fafo.ui.components",
        "",
        "// Generated by tools/trace-shield.py from fafo-shield2-FINAL-1024.png. Do not edit by hand.",
        "// SVG path data on a 1024 x 1024 viewport, drawn bottom to top with the even-odd fill rule.",
        "internal object ShieldPaths {",
        "    const val VIEWPORT = 1024f",
    ]
    for name, mask in layers.items():
        d = trace(mask)
        lines.append(f'    const val {name} = "{d}"')
        print(name, int(mask.sum()), "px,", len(d), "chars")
    lines += ["}", ""]
    with open(dst, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
